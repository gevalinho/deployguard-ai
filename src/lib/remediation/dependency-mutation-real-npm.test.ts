import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { validateDependencyMutation } from "./dependency-mutation-validator";
import type { VerifiedPatch } from "./verified-patch";

const fixtureDir = join(
  process.cwd(),
  "src/lib/remediation/__fixtures__/npm-braces-upgrade",
);

function readFixture(name: string): string {
  return readFileSync(join(fixtureDir, name), "utf8");
}

function realNpmPatch(): VerifiedPatch {
  return {
    fileCount: 2,
    files: [
      {
        path: "package.json",
        changeType: "modified",
        before: readFixture("package-before.json"),
        after: readFixture("package-after.json"),
      },
      {
        path: "package-lock.json",
        changeType: "modified",
        before: readFixture("package-lock-before.json"),
        after: readFixture("package-lock-after.json"),
      },
    ],
  };
}

describe("real npm lockfile regression", () => {
  it("accepts an authorized braces upgrade generated by npm", () => {
    const result = validateDependencyMutation(
      realNpmPatch(),
      "braces",
      "3.0.3",
    );

    expect(result.valid, result.reason).toBe(true);
  });

  it("rejects the same npm upgrade when the approved version differs", () => {
    const result = validateDependencyMutation(
      realNpmPatch(),
      "braces",
      "3.0.4",
    );

    expect(result.valid).toBe(false);
  });

  it("rejects unauthorized changes to an unrelated installed package", () => {
    const patch = realNpmPatch();
    const lockChange = patch.files.find(
      (file) => file.path === "package-lock.json",
    );

    if (!lockChange?.after) {
      throw new Error("Missing npm lockfile fixture.");
    }

    const lock = JSON.parse(lockChange.after);
    lock.packages["node_modules/fill-range"].version = "99.0.0";
    lockChange.after = JSON.stringify(lock);

    const result = validateDependencyMutation(
      patch,
      "braces",
      "3.0.3",
    );

    expect(result.valid).toBe(false);
  });
});

describe("npm package identity protection", () => {
  it("rejects a target tarball redirected to another package on the same registry", () => {
    const patch = realNpmPatch();
    const lockChange = patch.files.find(
      (file) => file.path === "package-lock.json",
    );

    if (!lockChange?.after) {
      throw new Error("Missing npm lockfile fixture.");
    }

    const lock = JSON.parse(lockChange.after);

    lock.packages["node_modules/braces"].resolved =
      "https://registry.npmjs.org/another-package/-/another-package-3.0.3.tgz";

    lockChange.after = JSON.stringify(lock);

    const result = validateDependencyMutation(
      patch,
      "braces",
      "3.0.3",
    );

    expect(result.valid).toBe(false);
  });
});
